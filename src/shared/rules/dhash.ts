/** 이 값 이하의 해밍거리면 같은 사진으로 본다 */
export const DUPLICATE_HAMMING = 5;

export function hamming(a: string, b: string): number {
  let d = 0;
  for (let i = 0; i < a.length; i++) {
    let x = parseInt(a[i], 16) ^ parseInt(b[i], 16);
    while (x) {
      d += x & 1;
      x >>= 1;
    }
  }
  return d;
}
